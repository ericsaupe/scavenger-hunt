import path from "node:path"
import { Clock, sleep } from "./lib/clock.js"
import { EventLog } from "./lib/events.js"
import { launchBrowser, Device } from "./lib/device.js"
import { RESULTS, PASSWORD } from "./config.js"

const [code, outName = "videoshow-" + Date.now()] = process.argv.slice(2)
const dir = path.join(RESULTS, outName)
const log = new EventLog(dir)
const clock = new Clock(1)
clock.start()
const shots = path.join(dir, "screenshots")
const browser = await launchBrowser({ headless: true })
const check = (label, ok, detail = "") => console.log(`${ok ? "PASS" : "FAIL"} ${label} ${detail}`)
const playback = (d) => d.page.locator("[data-controller~=playback]").first().evaluate((el) => `${el.dataset.playbackStateValue}:${el.dataset.playbackVersionValue}:${el.dataset.playbackMutedValue}`).catch(() => null)
const waitPlayback = (d, pred, ms = 6000) => d.page.waitForFunction((src) => { const el = document.querySelector("[data-controller~=playback]"); return el && new Function("s", `return ${src}`)(`${el.dataset.playbackStateValue}:${el.dataset.playbackVersionValue}:${el.dataset.playbackMutedValue}`) }, pred, { timeout: ms }).then(() => true).catch(() => false)

const screen = await new Device({ browser, name: "big-screen", kind: "big", log, clock, shots }).open()
const watcher = await new Device({ browser, name: "watcher", kind: "phone", log, clock, shots }).open()
const remote = await new Device({ browser, name: "remote", kind: "phone", log, clock, shots }).open()
await screen.goto(`/scavenger_hunts/${code}/presenter?screen=big`)
await watcher.goto(`/scavenger_hunts/${code}/presenter`)
await remote.goto(`/scavenger_hunts/${code}/presenter`)
await remote.page.click("summary:has-text('Take the remote')")
await remote.page.fill("input[name=password]", PASSWORD)
await Promise.all([remote.page.waitForURL(/\/presenter\/remote/, { timeout: 20000 }), remote.page.click("button:has-text('Take it')")])
check("took the remote", remote.page.url().includes("/remote"))

await remote.page.click("[data-testid=jump-to-item]")
const item = remote.page.locator("[data-testid=item-list] button", { hasText: "Construction" }).first()
await item.waitFor({ timeout: 5000 })
await item.click()
await remote.page.waitForFunction(() => document.querySelector("[data-testid=current-item]")?.textContent.includes("Construction"), null, { timeout: 10000 }).catch(() => null)
const before = await remote.text("[data-testid=progress]")
await remote.page.click("button:has-text('Next')")
await remote.page.waitForFunction((p) => document.querySelector("[data-testid=progress]")?.textContent.trim() !== p, before, { timeout: 10000 }).catch(() => null)
await sleep(1500)
const hasPlay = await remote.page.locator("[data-testid=play]").count()
check("remote shows play on the video slide", hasPlay === 1, await remote.text("[data-testid=current-item]"))
await screen.screenshot("video-waiting")
check("big screen holds the video paused", (await playback(screen))?.startsWith("paused"), await playback(screen))
const steps = [["play", "s.startsWith('playing')"], ["pause", "s.startsWith('paused')"], ["replay", "s.startsWith('playing:1')"], ["sound", "s.endsWith(':true') || s.endsWith(':false')"]]
for (const [button, pred] of steps) {
  const t = Date.now()
  const beforeState = await playback(screen)
  await remote.page.locator(`[data-testid=${button}]`).click()
  const okScreen = button === "sound" ? await screen.page.waitForFunction((b) => { const el = document.querySelector("[data-controller~=playback]"); return el && `${el.dataset.playbackStateValue}:${el.dataset.playbackVersionValue}:${el.dataset.playbackMutedValue}` !== b }, beforeState, { timeout: 6000 }).then(() => true).catch(() => false) : await waitPlayback(screen, pred)
  const tScreen = Date.now() - t
  const okWatcher = button === "sound" ? true : await waitPlayback(watcher, pred)
  check(`${button}: big screen ${await playback(screen)} watcher ${await playback(watcher)}`, okScreen && okWatcher, `${tScreen} ms`)
  await sleep(1500)
}
const videoPlaying = await screen.page.locator("video").first().evaluate((v) => ({ paused: v.paused, muted: v.muted, time: v.currentTime, ready: v.readyState })).catch(() => null)
check("big screen <video> element state", !!videoPlaying, JSON.stringify(videoPlaying))
await screen.screenshot("video-after-controls")

await remote.page.locator("[data-testid=screen-chat-switch]").check({ force: true })
await sleep(1500)
await remote.page.locator("[data-testid=announcements-only-switch]").check({ force: true })
const modeOk = await screen.page.waitForFunction(() => document.querySelector("[data-testid=screen-chat]")?.dataset.screenChatModeValue === "announcements", null, { timeout: 8000 }).then(() => true).catch(() => false)
check("big screen in announcements-only mode", modeOk)
const ownerPage = await remote.context.newPage()
const ownerPhone = Object.assign(Object.create(Object.getPrototypeOf(remote)), remote, { page: ownerPage, chatName: "Eric" })
await ownerPhone.goto(`/scavenger_hunts/${code}/presenter`)
const t1 = Date.now()
const annStatus = await ownerPhone.chat("Finale in five minutes, grab a drink.", { announcement: true, keepOpen: false }).catch((e) => String(e))
const annShown = await screen.page.locator("[data-testid=screen-chat-list] [data-message-id]", { hasText: "Finale in five" }).waitFor({ state: "attached", timeout: 8000 }).then(() => Date.now() - t1).catch(() => null)
check("announcement reaches the big-screen column in announcements mode", annStatus === 200 && annShown !== null, `${annStatus} ${annShown} ms`)
const chatStatus = await watcher.chat("ordinary chatter", { keepOpen: false }).catch((e) => String(e))
await sleep(3000)
const ordinaryShown = await screen.page.locator("[data-testid=screen-chat-list] [data-message-id]", { hasText: "ordinary chatter" }).count()
check("ordinary chat stays off the big screen in announcements mode", chatStatus === 200 && ordinaryShown === 0, `${chatStatus} shown=${ordinaryShown}`)
await screen.screenshot("announcements-only")
await remote.page.locator("[data-testid=announcements-only-switch]").uncheck({ force: true })
const backAll = await screen.page.waitForFunction(() => document.querySelector("[data-testid=screen-chat]")?.dataset.screenChatModeValue === "all", null, { timeout: 8000 }).then(() => true).catch(() => false)
check("back to all", backAll)
await browser.close()
await log.close()
console.log("dir:", dir)
process.exit(0)
